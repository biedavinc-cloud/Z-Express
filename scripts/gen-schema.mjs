#!/usr/bin/env node
// Generates supabase/migrations/0001_init.sql from supabase/entities/*.jsonc.
//
// Every entity is stored in one `records` table (entity name + jsonb payload).
// The per-entity access rules found in each *.jsonc ("rls") are translated into
// Postgres row-level-security policies, so the database itself enforces tenant
// isolation — the browser is never trusted.
//
// Usage: node scripts/gen-schema.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entitiesDir = join(root, 'supabase', 'entities');
const outFile = join(root, 'supabase', 'migrations', '0001_init.sql');
const staticFile = join(root, 'supabase', 'migrations', 'static', 'core.sql');

const stripComments = (text) => text.replace(/^\s*\/\/.*$/gm, '');
const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;
const FIELD = /^[A-Za-z_][A-Za-z0-9_]*$/;

const entities = readdirSync(entitiesDir)
  .filter((file) => file.endsWith('.jsonc'))
  .sort()
  .map((file) => JSON.parse(stripComments(readFileSync(join(entitiesDir, file), 'utf8'))));

function placeholder(value) {
  if (value === '{{user.email}}') return 'app_email()';
  if (value === '{{user.id}}') return 'auth.uid()';
  throw new Error(`Unsupported rule placeholder: ${value}`);
}

// Translate one access-rule condition into a SQL boolean expression.
function condition(node) {
  if (!node || Object.keys(node).length === 0) return 'true';
  const parts = Object.entries(node).map(([key, value]) => {
    if (key === '$or') return `(${value.map(condition).join(' OR ')})`;
    if (key === '$and') return `(${value.map(condition).join(' AND ')})`;
    if (key === 'user_condition') {
      if (value.role === 'admin' && Object.keys(value).length === 1) return 'app_is_admin()';
      throw new Error(`Unsupported user_condition: ${JSON.stringify(value)}`);
    }
    if (key === 'created_by_id') return `created_by_id = ${placeholder(value)}`;
    if (key.startsWith('data.')) {
      const field = key.slice(5);
      if (!FIELD.test(field)) throw new Error(`Bad field name: ${field}`);
      if (value === '{{user.email}}') return `app_has_email(data->${sqlString(field)})`;
      if (value === '{{user.id}}') return `data->>${sqlString(field)} = auth.uid()::text`;
      if (value && Array.isArray(value.$in) && value.$in.length === 1 && value.$in[0] === '{{user.email}}') {
        return `app_has_email(data->${sqlString(field)})`;
      }
    }
    throw new Error(`Unsupported rule: ${key} => ${JSON.stringify(value)}`);
  });
  return parts.length === 1 ? parts[0] : `(${parts.join(' AND ')})`;
}

const names = entities.map((entity) => entity.name);
const lines = [];
lines.push('-- GENERATED by scripts/gen-schema.mjs — do not edit by hand.');
lines.push('-- Edit supabase/entities/*.jsonc or supabase/migrations/static/core.sql, then re-run the generator.');
lines.push('');
lines.push(readFileSync(staticFile, 'utf8').replace('/*ENTITY_NAMES*/', names.map(sqlString).join(', ')));
lines.push('');
lines.push('-- ===== Row-level security, one set of policies per entity =====');

for (const entity of entities) {
  const rls = entity.rls || {};
  const entityLiteral = sqlString(entity.name);
  lines.push('');
  lines.push(`-- ${entity.name}`);
  for (const op of ['read', 'create', 'update', 'delete']) {
    if (!rls[op]) continue;
    const open = Object.keys(rls[op]).length === 0;
    const expr = condition(rls[op]);
    const policy = `"${entity.name}_${op}"`;
    // A rule that is literally {} opens the operation to anonymous visitors
    // (contact form, public partner logos). Everything else needs a session.
    const role = open ? 'anon, authenticated' : 'authenticated';
    if (op === 'read') {
      lines.push(`create policy ${policy} on public.records for select to ${role} using (entity = ${entityLiteral} and ${expr});`);
    } else if (op === 'create') {
      lines.push(`create policy ${policy} on public.records for insert to ${role} with check (entity = ${entityLiteral} and ${expr});`);
    } else if (op === 'update') {
      lines.push(
        `create policy ${policy} on public.records for update to ${role} using (entity = ${entityLiteral} and ${expr}) with check (entity = ${entityLiteral});`
      );
    } else {
      lines.push(`create policy ${policy} on public.records for delete to ${role} using (entity = ${entityLiteral} and ${expr});`);
    }
  }
}

writeFileSync(outFile, lines.join('\n') + '\n');
console.log(`Wrote ${outFile} (${entities.length} entities)`);
